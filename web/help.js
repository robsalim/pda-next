function helpAddressReference() {
    if (!driverTypes.length) return `<p style="color:var(--warn)">Справочник адресов недоступен (сервер не отвечает).</p>`;
    let html = '';
    for (const t of driverTypes) {
        const ex = (t.address && t.address.examples) || [];
        html += `<h3>${escHtml(t.label || t.key)}</h3><table><tr><th>Адрес</th><th>Тип</th><th>Что читается</th></tr>`;
        for (const row of ex) {
            html += `<tr><td><code>${escHtml(row[0])}</code></td><td>${escHtml(row[1])}</td><td>${escHtml(row[2] || '')}</td></tr>`;
        }
        html += `</table>`;
    }
    return html;
}

async function renderHelp() {
    const host = document.getElementById('help-body');
    host.innerHTML = HELP_SECTIONS.replace('__ADDRESS_REFERENCE__', `<p style="color:var(--text-faint)">Загрузка справочника адресов…</p>`);
    // driverTypes уже должен быть загружен init()ом; на случай медленного старта — повтор.
    if (!driverTypes.length) {
        try { driverTypes = (await apiGet('/api/drivers/info')).types || []; } catch (e) { /* справочник останется пустым */ }
    }
    host.innerHTML = HELP_SECTIONS.replace('__ADDRESS_REFERENCE__', helpAddressReference());
}
